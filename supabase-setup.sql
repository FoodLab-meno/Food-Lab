-- FoodLab: جدول و دسترسی‌های مدیریت محصولات
-- قبل از اجرا، حساب مدیر را در Supabase Authentication > Users بساز.
-- هر سه عبارت PASTE_ADMIN_USER_ID_HERE را با UUID همان حساب جایگزین کن.

create table if not exists public.products (
 id bigint generated by default as identity primary key,
 category_id text not null check(category_id in ('breakfast','sandwich','appetizer','cafe','drinks')),
 name text not null,
 description text default '',
 price bigint check(price is null or price >= 0),
 active boolean not null default true,
 sort_order integer not null default 0,
 created_at timestamptz not null default now()
);

-- برای نصب‌هایی که جدول قبلاً ساخته شده، ستون‌های لازم را تضمین کن.
alter table public.products add column if not exists description text default '';
alter table public.products add column if not exists sort_order integer not null default 0;
alter table public.products enable row level security;

drop policy if exists "Public read active products" on public.products;
drop policy if exists "Only owner can read all products" on public.products;
drop policy if exists "Only owner can update products" on public.products;
drop policy if exists "Only owner can insert products" on public.products;

-- عموم فقط محصولات فعال را می‌بینند؛ مدیر تمام محصولات را می‌بیند.
create policy "Public read active products" on public.products
for select to anon, authenticated using (active = true);

create policy "Only owner can read all products" on public.products
for select to authenticated
using (auth.uid() = '6a8e56d1-39a5-4e59-9bce-4c9571a57b43'::uuid);

-- فقط مدیر مجاز به افزودن و ویرایش محصول است.
create policy "Only owner can insert products" on public.products
for insert to authenticated
with check (auth.uid() = '6a8e56d1-39a5-4e59-9bce-4c9571a57b43'::uuid);

create policy "Only owner can update products" on public.products
for update to authenticated
using (auth.uid() = '6a8e56d1-39a5-4e59-9bce-4c9571a57b43'::uuid)
with check (auth.uid() = '6a8e56d1-39a5-4e59-9bce-4c9571a57b43'::uuid);

