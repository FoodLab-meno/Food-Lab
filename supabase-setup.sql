-- 1) در Supabase > SQL Editor اجرا کن.
-- 2) پیش از اجرای این فایل، حساب مدیر را در Authentication > Users بساز.
-- 3) مقدار PASTE_ADMIN_USER_ID_HERE را با UUID همان کاربر جایگزین کن.

create table if not exists public.products (
 id bigint generated by default as identity primary key,
 category_id text not null check(category_id in ('breakfast','sandwich','appetizer','cafe','drinks')),
 name text not null,
 description text default '',
 price bigint check(price is null or price >= 0),
 active boolean not null default true,
 sort_order integer not null default 0,
 created_at timestamptz not null default now()
);

alter table public.products enable row level security;

drop policy if exists "Public read active products" on public.products;
drop policy if exists "Authenticated update products" on public.products;
drop policy if exists "Only owner can read all products" on public.products;
drop policy if exists "Only owner can update products" on public.products;

-- همه فقط محصولات فعال را می‌بینند؛ مدیر مشخص‌شده همه محصولات را می‌بیند.
create policy "Public read active products" on public.products
for select using (active = true);

create policy "Only owner can read all products" on public.products
for select to authenticated
using (auth.uid() = 'PASTE_ADMIN_USER_ID_HERE'::uuid);

-- فقط حساب مدیر مشخص‌شده می‌تواند قیمت یا وضعیت نمایش را تغییر دهد.
create policy "Only owner can update products" on public.products
for update to authenticated
using (auth.uid() = 'PASTE_ADMIN_USER_ID_HERE'::uuid)
with check (auth.uid() = 'PASTE_ADMIN_USER_ID_HERE'::uuid);

